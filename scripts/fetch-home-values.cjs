// Fetches Zillow's Home Value Index (ZHVI) for every state and the U.S. and writes
// src/data/homeValues.ts, which sets each calculator's local home price.
//
// Three price tiers, all smoothed and seasonally adjusted, single-family + condo:
//   entry   = bottom tier (homes in the 5th–35th percentile of value)
//   typical = middle tier (35th–65th percentile), Zillow's headline "typical home value"
//   upper   = top tier (65th–95th percentile)
// Zillow publishes monthly; the weekly rate refresh runs this too, so a new month is
// picked up within a week. If a download fails or looks wrong, the committed file is
// kept, so a build never breaks or ships empty values.
const fs = require("fs");
const path = require("path");

const BASE = "https://files.zillowstatic.com/research/public_csvs/zhvi";
const TIERS = { entry: "0.0_0.33", typical: "0.33_0.67", upper: "0.67_1.0" };
const OUT = path.join(__dirname, "..", "src", "data", "homeValues.ts");
const MONTHS = 13; // this month and the same month a year ago

// State names and codes from the site's own state list.
const STATES_SRC = fs.readFileSync(path.join(__dirname, "..", "src", "lib", "states.ts"), "utf8");
const CODES = Object.fromEntries([...STATES_SRC.matchAll(/name: "([^"]+)", code: "([A-Z]{2})"/g)].map((m) => [m[1], m[2]]));

/** Split one CSV line, honoring quoted fields ("New York, NY"). */
function splitCsv(line) {
  const out = [];
  let cur = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"') {
      if (quoted && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else quoted = !quoted;
    } else if (c === "," && !quoted) {
      out.push(cur);
      cur = "";
    } else cur += c;
  }
  out.push(cur);
  return out;
}

/** { header dates, rows: name -> numbers (null where missing) } */
function parse(csv) {
  const lines = csv.split(/\r?\n/).filter(Boolean);
  const head = splitCsv(lines[0]);
  const first = head.findIndex((h) => /^\d{4}-\d{2}-\d{2}$/.test(h));
  const nameCol = head.indexOf("RegionName");
  const dates = head.slice(first);
  const rows = new Map();
  for (const line of lines.slice(1)) {
    const cols = splitCsv(line);
    rows.set(cols[nameCol], cols.slice(first).map((v) => (v === "" ? null : Number(v))));
  }
  return { dates, rows };
}

async function get(url) {
  const res = await fetch(url, { headers: { "User-Agent": "mortgagecalculation.net build" }, signal: AbortSignal.timeout(60000) });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return parse(await res.text());
}

const round100 = (v) => Math.round(v / 100) * 100;

async function main() {
  const tiers = {};
  try {
    for (const [tier, band] of Object.entries(TIERS)) {
      const [state, metro] = await Promise.all([
        get(`${BASE}/State_zhvi_uc_sfrcondo_tier_${band}_sm_sa_month.csv`),
        get(`${BASE}/Metro_zhvi_uc_sfrcondo_tier_${band}_sm_sa_month.csv`),
      ]);
      tiers[tier] = { state, metro };
    }
  } catch (err) {
    console.warn(`fetch-home-values: download failed (${err.message}); keeping the committed values.`);
    return;
  }

  const { dates } = tiers.typical.state;
  const asOf = dates[dates.length - 1];

  /** Latest values for one region, or null if any tier is missing this month. */
  const region = (name, source) => {
    const out = {};
    for (const tier of Object.keys(TIERS)) {
      const series = tiers[tier][source].rows.get(name);
      const latest = series?.[series.length - 1];
      if (!(latest > 0)) return null;
      out[tier] = round100(latest);
    }
    const typical = tiers.typical[source].rows.get(name).slice(-MONTHS);
    if (typical.some((v) => !(v > 0))) return null;
    out.history = typical.map(round100);
    return out;
  };

  const national = region("United States", "metro");
  const states = {};
  for (const [name, code] of Object.entries(CODES)) {
    const r = region(name, "state");
    if (r) states[code] = r;
  }

  // Sanity checks: recent month, nearly every state, believable values.
  const ageDays = (Date.now() - Date.parse(asOf)) / 86_400_000;
  const values = Object.values(states);
  const believable = values.every((s) => s.entry < s.typical && s.typical < s.upper && s.typical > 50_000 && s.typical < 3_000_000);
  if (!national || values.length < 45 || ageDays > 120 || !believable) {
    console.warn(`fetch-home-values: data looks wrong or stale (${values.length} states, ${asOf}); keeping the committed values.`);
    return;
  }

  const data = {
    source: "Zillow Home Value Index",
    sourceUrl: "https://www.zillow.com/research/data/",
    asOf,
    national,
    states,
  };
  const body = `// Generated by scripts/fetch-home-values.cjs from Zillow's ZHVI. Do not edit by hand.
import type { HomeValues } from "../lib/localCosts.ts";

export const HOME_VALUES: HomeValues = ${JSON.stringify(data)};
`;
  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (before !== body) fs.writeFileSync(OUT, body);
  const missing = Object.values(CODES).filter((c) => !states[c]);
  console.log(
    `fetch-home-values: U.S. typical $${national.typical.toLocaleString()} as of ${asOf}, ${values.length} states` +
      `${missing.length ? ` (missing ${missing.join(", ")}: they use U.S. values)` : ""}${before === body ? " (unchanged)" : ""}.`,
  );
}

main().catch((err) => console.warn(`fetch-home-values: ${err.message}; keeping the committed values.`));
