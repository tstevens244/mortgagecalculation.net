// Fetches Freddie Mac's weekly Primary Mortgage Market Survey (PMMS) and writes
// src/data/marketRates.ts, which the calculators use for "today's average rate".
// Runs before every build; the deploy workflow also runs weekly after Freddie Mac
// publishes (Thursdays, or Wednesday in holiday weeks). If the download fails, the
// committed file is kept, so a build never breaks or ships empty rates.
const fs = require("fs");
const path = require("path");

const SOURCE = "https://www.freddiemac.com/pmms/docs/PMMS_history.csv";
const OUT = path.join(__dirname, "..", "src", "data", "marketRates.ts");
const WEEKS = 52;

const unquote = (s) => s.replace(/^"|"$/g, "").trim();

/** "11/25/2026" -> "2026-11-25" */
function isoDate(us) {
  const [m, d, y] = us.split("/").map(Number);
  if (!y || !m || !d) return null;
  return `${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
}

function parse(csv) {
  const rows = [];
  for (const line of csv.split(/\r?\n/).slice(1)) {
    const cols = line.split(",").map(unquote);
    const date = isoDate(cols[0] || "");
    const r30 = Number(cols[1]);
    const r15 = Number(cols[3]);
    if (!date || !(r30 > 0) || !(r15 > 0)) continue;
    rows.push({ date, r30, r15 });
  }
  return rows.sort((a, b) => a.date.localeCompare(b.date));
}

